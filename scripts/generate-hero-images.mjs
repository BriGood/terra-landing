// Generates the responsive hero variants committed under
// public/Branding/responsive/.
//
// Local /Branding assets are served straight off the ASSETS binding — the Next
// image optimizer does not run on Cloudflare Workers without an IMAGES binding
// (see lib/shopify-image-loader.ts), so nothing resizes or re-encodes these at
// request time. They are built here and committed.
//
// Run after replacing either hero master:  npm run images
//
// Widths never exceed the source: upscaling adds bytes and no detail.

import sharp from 'sharp';
import { mkdir, readdir, unlink, writeFile } from 'node:fs/promises';
import { statSync } from 'node:fs';
import path from 'node:path';

const OUT = 'public/Branding/responsive';

const SOURCES = [
  // Desktop art direction, shown at >=768px. 2560/3000 cover 2x laptops.
  // 5:1 master, matching the hero box above 1320px so it fills edge to edge.
  { src: 'public/Branding/Hero_Desktop.jpg', name: 'hero-desktop', widths: [1280, 1920, 2560, 3000] },
  // Mobile art direction, shown below 768px. 1000 is the source width, so that
  // is the ceiling — a 390px phone at 3x wants 1170 and gets the native 1000.
  { src: 'public/Branding/Hero_Mobile.jpg', name: 'hero-mobile', widths: [500, 750, 1000] },
];

// AVIF carries this image far better than WebP does (measured on the previous
// banner: WebP actually lost to a good JPEG on dense texture), so AVIF is the
// primary and WebP is the compatibility fallback.
const FORMATS = [
  { ext: 'avif', encode: (p) => p.avif({ quality: 55 }) },
  { ext: 'webp', encode: (p) => p.webp({ quality: 78 }) },
];

await mkdir(OUT, { recursive: true });

// Clear previously generated files so a renamed or dropped source can't leave
// orphans behind that the markup still points at.
for (const file of await readdir(OUT)) {
  await unlink(path.join(OUT, file));
}

for (const { src, name, widths } of SOURCES) {
  const meta = await sharp(src).metadata();
  console.log(`\n${src}  ${meta.width}x${meta.height}  (${(meta.width / meta.height).toFixed(2)}:1)`);

  for (const width of widths) {
    if (width > meta.width) {
      console.log(`  skip ${width}w — wider than the source`);
      continue;
    }
    for (const { ext, encode } of FORMATS) {
      const out = path.join(OUT, `${name}-${width}.${ext}`);
      await encode(sharp(src).resize(width)).toFile(out);
      console.log(`  ${path.basename(out).padEnd(26)} ${(statSync(out).size / 1024).toFixed(0).padStart(5)} KB`);
    }
  }
}

// --- Open Graph card background ------------------------------------------
//
// The share card (app/opengraph-image.tsx) is drawn by Satori, which needs the
// image bytes in hand: there is no filesystem on Workers and fetching our own
// public URL during a build would make the build depend on the site it is
// building. So the crop is inlined as a data URI in a generated module.
//
// 1200x630 is 1.905:1 against the master's 5:1, so this takes a 1143x600
// window rather than scaling. It starts at x=1500 to put the figure right of
// centre and the lit ground low-left, leaving the upper left dark for type.

const OG = { width: 1200, height: 630, window: { left: 1500, top: 0, width: 1143, height: 600 } };
const OG_MODULE = 'lib/og-card.ts';

const ogBuffer = await sharp('public/Branding/Hero_Desktop.jpg')
  .extract(OG.window)
  .resize(OG.width, OG.height)
  .jpeg({ quality: 82 })
  .toBuffer();

await writeFile(
  OG_MODULE,
  `// GENERATED by scripts/generate-hero-images.mjs — do not edit by hand.\n` +
    `// Run \`npm run images\` after replacing public/Branding/Hero_Desktop.jpg.\n` +
    `// See that script for why this is inlined rather than read or fetched.\n` +
    `export const OG_CARD_WIDTH = ${OG.width};\n` +
    `export const OG_CARD_HEIGHT = ${OG.height};\n` +
    `export const OG_CARD_BACKGROUND =\n  'data:image/jpeg;base64,${ogBuffer.toString('base64')}';\n`
);

console.log(`\n${OG_MODULE}  ${OG.width}x${OG.height}  ${(ogBuffer.length / 1024).toFixed(0)} KB raw`);
